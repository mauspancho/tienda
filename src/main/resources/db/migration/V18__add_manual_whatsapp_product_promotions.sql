create table whatsapp_manual_promotion (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    tenant_id bigint not null,
    product_id bigint not null,
    user_id bigint not null,
    connection_id bigint not null,
    request_key varchar(80) not null,
    message text not null,
    status varchar(24) not null,
    accepted_count integer not null default 0,
    failed_count integer not null default 0,
    primary key (id),
    unique key uk_whatsapp_manual_promotion_request (tenant_id, request_key),
    key idx_whatsapp_manual_promotion_tenant_created (tenant_id, created_at),
    key idx_whatsapp_manual_promotion_product_created (product_id, created_at),
    key idx_whatsapp_manual_promotion_user (user_id),
    key idx_whatsapp_manual_promotion_connection (connection_id),
    constraint fk_whatsapp_manual_promotion_tenant foreign key (tenant_id) references tenant(id),
    constraint fk_whatsapp_manual_promotion_product foreign key (product_id) references product(id),
    constraint fk_whatsapp_manual_promotion_user foreign key (user_id) references app_user(id),
    constraint fk_whatsapp_manual_promotion_connection foreign key (connection_id) references tenant_whatsapp_connection(id)
) engine=InnoDB default charset=utf8mb4;

create table whatsapp_manual_promotion_delivery (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    promotion_id bigint not null,
    group_id bigint not null,
    group_name varchar(255) not null,
    status varchar(24) not null,
    provider_message_id varchar(255),
    error_message varchar(500),
    primary key (id),
    unique key uk_whatsapp_manual_promotion_delivery_group (promotion_id, group_id),
    key idx_whatsapp_manual_promotion_delivery_group (group_id),
    constraint fk_whatsapp_manual_promotion_delivery_promotion foreign key (promotion_id) references whatsapp_manual_promotion(id),
    constraint fk_whatsapp_manual_promotion_delivery_group foreign key (group_id) references whatsapp_group(id)
) engine=InnoDB default charset=utf8mb4;
