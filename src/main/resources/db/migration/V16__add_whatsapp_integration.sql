create table whatsapp_provider (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    name varchar(120) not null,
    base_url varchar(500) not null,
    encrypted_secret varchar(2048) not null,
    enabled bit not null default 1,
    status varchar(40) not null default 'NOT_CHECKED',
    last_checked_at datetime(6),
    last_error varchar(500),
    primary key (id),
    unique key uk_whatsapp_provider_name (name)
) engine=InnoDB default charset=utf8mb4;

create table tenant_whatsapp_connection (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    tenant_id bigint not null,
    provider_id bigint not null,
    session_name varchar(100) not null,
    encrypted_session_token varchar(4096) not null,
    phone_number varchar(40),
    status varchar(40) not null default 'NOT_CONFIGURED',
    last_connected_at datetime(6),
    last_checked_at datetime(6),
    last_error varchar(500),
    primary key (id),
    unique key uk_tenant_whatsapp_connection_tenant (tenant_id),
    unique key uk_tenant_whatsapp_connection_tenant_id (tenant_id, id),
    unique key uk_tenant_whatsapp_connection_provider_session (provider_id, session_name),
    key idx_tenant_whatsapp_connection_provider (provider_id),
    constraint fk_tenant_whatsapp_connection_tenant foreign key (tenant_id) references tenant(id),
    constraint fk_tenant_whatsapp_connection_provider foreign key (provider_id) references whatsapp_provider(id)
) engine=InnoDB default charset=utf8mb4;

create table whatsapp_group (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    tenant_id bigint not null,
    connection_id bigint not null,
    whatsapp_id varchar(180) not null,
    name varchar(255) not null,
    participant_count integer,
    available bit not null default 1,
    refreshed_at datetime(6) not null,
    primary key (id),
    unique key uk_whatsapp_group_tenant_whatsapp_id (tenant_id, whatsapp_id),
    key idx_whatsapp_group_connection (connection_id),
    constraint fk_whatsapp_group_connection foreign key (tenant_id, connection_id) references tenant_whatsapp_connection(tenant_id, id)
) engine=InnoDB default charset=utf8mb4;

create table tenant_integration_token (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    tenant_id bigint not null,
    name varchar(120) not null,
    token_prefix varchar(24) not null,
    token_hash varchar(64) not null,
    scopes varchar(255) not null,
    active bit not null default 1,
    last_used_at datetime(6),
    revoked_at datetime(6),
    expires_at datetime(6),
    primary key (id),
    unique key uk_tenant_integration_token_hash (token_hash),
    unique key uk_tenant_integration_token_tenant_id (tenant_id, id),
    key idx_tenant_integration_token_tenant_active (tenant_id, active),
    constraint fk_tenant_integration_token_tenant foreign key (tenant_id) references tenant(id)
) engine=InnoDB default charset=utf8mb4;

create table integration_idempotency_record (
    id bigint not null auto_increment,
    version bigint,
    created_at datetime(6) not null,
    updated_at datetime(6) not null,
    created_by varchar(255),
    updated_by varchar(255),
    tenant_id bigint not null,
    token_id bigint not null,
    operation_name varchar(80) not null,
    key_hash varchar(64) not null,
    request_hash varchar(64) not null,
    response_json longtext not null,
    primary key (id),
    unique key uk_integration_idempotency (tenant_id, token_id, operation_name, key_hash),
    key idx_integration_idempotency_token (token_id),
    key idx_integration_idempotency_created (created_at),
    constraint fk_integration_idempotency_token foreign key (tenant_id, token_id) references tenant_integration_token(tenant_id, id)
) engine=InnoDB default charset=utf8mb4;
